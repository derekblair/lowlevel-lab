#!/usr/bin/env bash
# repro.sh — clean-clone reproduction setup for the reviewer lane (REVIEW-00 §2.2).
#
# usage: review/tools/repro.sh LABEL COMMIT
#
# Clones the local repo fresh into tasks/reviewer-repro/LABEL (never builds in
# the shared standing tree), checks out COMMIT, creates an isolated HOME and an
# evidence dir, and writes tasks/reviewer-repro/LABEL/.envrun: a wrapper that
# runs a command under `env -i` with a minimal PATH, the isolated HOME, no core
# dumps and a timeout. Usage after setup:
#
#   C=tasks/reviewer-repro/LABEL
#   (cd $C/parts/NN-slug && ../../.envrun make)            # plain run
#   (cd $C/parts/NN-slug && STRACE=1 ../../.envrun make)   # traced run -> .evidence/strace.log
#
# The clone holds only committed state, so uncommitted author work is never
# what gets reviewed (REVIEW-00 §1.10).
set -eu
label=${1:?label}; commit=${2:?commit}
top=$(cd "$(dirname "$0")/../.." && pwd)
C=$top/tasks/reviewer-repro/$label
[ -e "$C" ] && { echo "refusing: $C exists (pick a new label)" >&2; exit 1; }
git clone -q --no-hardlinks "$top" "$C"
git -C "$C" -c advice.detachedHead=false checkout -q "$commit"
mkdir -p "$C/.home" "$C/.evidence"
cat > "$C/.envrun" <<EOF
#!/usr/bin/env bash
# generated by review/tools/repro.sh for $label @ $commit
ulimit -c 0
T=\${TIMEOUT:-900}
if [ -n "\${STRACE:-}" ]; then
  exec env -i HOME="$C/.home" PATH=/usr/local/bin:/usr/bin:/bin LANG=C.UTF-8 TERM=dumb \\
    timeout "\$T" strace -f -qq -o "$C/.evidence/strace.log" \\
      -e trace=open,openat,creat,rename,renameat,renameat2,unlink,unlinkat,mkdir,mkdirat,rmdir,symlink,symlinkat,link,linkat,truncate,chmod,fchmodat,chdir,connect,sendto,sendmsg,bind,socket,execve,execveat,ptrace,process_vm_writev "\$@"
fi
exec env -i HOME="$C/.home" PATH=/usr/local/bin:/usr/bin:/bin LANG=C.UTF-8 TERM=dumb timeout "\$T" "\$@"
EOF
chmod +x "$C/.envrun"
{ echo "label=$label commit=$commit head=$(git -C "$C" rev-parse HEAD) at=$(date '+%F %T %Z')"
  git -C "$C" status --porcelain | sed 's/^/status: /'; } | tee "$C/.evidence/setup.txt"
echo "clone: $C"
